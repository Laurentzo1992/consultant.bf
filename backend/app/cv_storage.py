"""Storage of consultants' CVs (PDF) on the local filesystem.

Files are saved under settings.upload_dir with a random name, so a stored
name never reveals who the CV belongs to and can't be guessed. They are
never served statically: the routers stream them only to the profile owner,
or to a company once a connection has been approved.
"""

import secrets
from pathlib import Path

from fastapi import HTTPException, UploadFile, status

from app.config import settings

PDF_MAGIC = b"%PDF-"
CHUNK = 64 * 1024


def _dir() -> Path:
    path = Path(settings.upload_dir) / "cv"
    path.mkdir(parents=True, exist_ok=True)
    return path


def path_of(filename: str) -> Path:
    # Stored names are generated by us (token + ".pdf"); `.name` guards
    # against any path component sneaking in anyway.
    return _dir() / Path(filename).name


def save_pdf(upload: UploadFile) -> str:
    """Validates and stores the uploaded PDF, returning its stored file name."""
    head = upload.file.read(len(PDF_MAGIC))
    if head != PDF_MAGIC:
        raise HTTPException(status.HTTP_400_BAD_REQUEST, "Le CV doit etre un fichier PDF")

    filename = f"{secrets.token_hex(16)}.pdf"
    target = path_of(filename)
    size = len(head)
    try:
        with target.open("wb") as out:
            out.write(head)
            while chunk := upload.file.read(CHUNK):
                size += len(chunk)
                if size > settings.cv_max_bytes:
                    raise HTTPException(
                        status.HTTP_413_REQUEST_ENTITY_TOO_LARGE,
                        f"Le CV ne doit pas depasser {settings.cv_max_bytes // (1024 * 1024)} Mo",
                    )
                out.write(chunk)
    except BaseException:
        target.unlink(missing_ok=True)
        raise
    return filename


def delete(filename: str | None) -> None:
    if filename:
        path_of(filename).unlink(missing_ok=True)
